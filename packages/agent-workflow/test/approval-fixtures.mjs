// Offline approval fixtures: a ticket approved by a trusted brief and not
// edited since ready-for-agent was applied, unless overrides say otherwise.
export const READY_AT = "2026-01-10T12:00:00Z";

export function approved(overrides = {}) {
	return {
		url: "https://github.com/example/project/issues/1",
		authorAssociation: "NONE",
		bodyEditedAt: null,
		titleEditedAt: null,
		readyLabeledAt: READY_AT,
		comments: [
			{
				url: "https://github.com/example/project/issues/1#issuecomment-1",
				authorAssociation: "OWNER",
				createdAt: "2026-01-10T11:59:00Z",
				lastEditedAt: null,
				body: "> *This was generated by AI during triage.*\n\n## Agent Brief\n\nDo the thing.",
			},
		],
		...overrides,
	};
}

// Raw gh responses for the approval queries, for fakes that stand in for gh
// itself. Returns undefined for any other call.
export function approvalResponse(args, approval = approved()) {
	if (args[0] === "api" && args[1] === "graphql")
		return JSON.stringify([
			{
				data: {
					repository: {
						issue: {
							url: approval.url,
							authorAssociation: approval.authorAssociation,
							lastEditedAt: approval.bodyEditedAt,
							comments: {
								pageInfo: { hasNextPage: false, endCursor: null },
								nodes: approval.comments,
							},
						},
					},
				},
			},
		]);
	if (args[0] === "api" && /\/issues\/\d+\/events\?/.test(args.at(-1)))
		return JSON.stringify([
			[
				{
					event: "labeled",
					label: { name: "ready-for-agent" },
					created_at: approval.readyLabeledAt,
				},
				...(approval.titleEditedAt
					? [{ event: "renamed", created_at: approval.titleEditedAt }]
					: []),
			],
		]);
	return undefined;
}
